import { readFile, writeFile } from "node:fs/promises";
import { Ajv } from "ajv";
import standalone from "ajv/dist/standalone/index.js";

const schema = JSON.parse(
  await readFile(new URL("../packages/rule-ir/schema.json", import.meta.url), "utf8"),
);
const ajv = new Ajv({
  strict: false,
  allErrors: true,
  code: { source: true, esm: true, lines: true },
});
let code = standalone(ajv, ajv.compile(schema));
// AJV's standalone helper is static; replace its CJS import for a pure ESM artifact.
code = code.replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2Exports.default");
if (/\brequire\(/.test(code))
  throw new Error("Unexpected validator runtime dependency; review generator before release");
const output = `// @ts-nocheck\n// Generated by scripts/generate-validator.mjs. Never edit; no runtime eval.\nimport ucs2Exports from "ajv/dist/runtime/ucs2length.js";\n${code.trimEnd()}\n`;
const target = new URL("../packages/rule-ir/validator.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== output)
    throw new Error("Schema validator is stale; run npm run schema:generate");
} else await writeFile(target, output);
